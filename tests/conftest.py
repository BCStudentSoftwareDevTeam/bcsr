"""Configure before application imports; never read normal database credentials."""
import os
from pathlib import Path
import sys
import tempfile
import uuid

import pymysql
import pytest
import yaml


def pytest_configure(config):
    if 'app' in sys.modules:
        raise pytest.UsageError('BCSR was imported before isolated test configuration.')
    config._bcsr_original_config = os.environ.get('BCSR_SECRET_CONFIG')
    config._bcsr_temp = tempfile.TemporaryDirectory(prefix='bcsr-tests-')
    db = {
        'db_name': 'bcsr_test_' + uuid.uuid4().hex,
        'host': os.environ.get('BCSR_TEST_MYSQL_HOST', '127.0.0.1'),
        'port': int(os.environ.get('BCSR_TEST_MYSQL_PORT', '3306')),
        'username': os.environ.get('BCSR_TEST_MYSQL_USER', 'bcsr_test'),
        'password': os.environ.get('BCSR_TEST_MYSQL_PASSWORD', ''),
    }
    if os.environ.get('BCSR_TEST_MYSQL_SOCKET'):
        db['unix_socket'] = os.environ['BCSR_TEST_MYSQL_SOCKET']
    config._bcsr_db = db
    path = Path(config._bcsr_temp.name) / 'config.yaml'
    path.write_text(yaml.safe_dump({'secret_key': 'test-only-session-key', 'db': db}))
    path.chmod(0o600)
    os.environ['BCSR_SECRET_CONFIG'] = str(path)


def pytest_unconfigure(config):
    if hasattr(config, '_bcsr_temp'):
        original = config._bcsr_original_config
        if original is None:
            os.environ.pop('BCSR_SECRET_CONFIG', None)
        else:
            os.environ['BCSR_SECRET_CONFIG'] = original
        config._bcsr_temp.cleanup()


